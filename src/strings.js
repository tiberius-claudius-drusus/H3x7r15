/** Français et anglais, par code (les autres langues se chargent par `src/lang/index.js`). */
export const STRINGS = { fr: FR, en: EN };

let dictionary = FR;

/** Choisit le dictionnaire courant (un objet clé -> texte). */
export function setDictionary(dict) { dictionary = dict ?? FR; }

export function t(key, params = {}) {
  const text = dictionary[key] ?? EN[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m));
}

/** Durée en secondes -> « m:ss » ou « h:mm:ss ». */
export function formatTime(seconds) {
  const s = Math.max(0, Math.floor(seconds));
  const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), r = s % 60;
  return h > 0 ? `${h}:${String(m).padStart(2, '0')}:${String(r).padStart(2, '0')}` : `${m}:${String(r).padStart(2, '0')}`;
}
